// service -> generator
const GEN = {
  profiles,
  settings,
  calendar,
  projects,
  files,
  "search-rag": searchRag,
  "ai-gateway": aiGateway,
  agent,
  email,
  "external-calendars": externalCalendars,
  integrations,
  "time-tracking": timeTracking,
  "export-import": exportImport,
  sync,
};

let count = 0;
for (const [name, gen] of Object.entries(GEN)) {
  const target = join(ROOT, "services", name, "src", "db", "schema.ts");
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, gen());
  count++;
}
console.log(`Generated full Drizzle schemas for ${count} services.`);
