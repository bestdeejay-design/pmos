#!/usr/bin/env node
/**
 * gen-schemas.mjs — generates full Drizzle ORM schemas for the 14 remaining PMOS services.
 * Already-authored samples: services/notes (notes/templates/note_links),
 * services/tasks (tasks/task_dependencies). This script covers the rest, matching
 * FEATURES.md entities + ADR-004 schema-per-service isolation (cross-service refs are UUIDs only).
 * Idempotent: overwrites each service's src/db/schema.ts.
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, "..");

// Common column builders (keep style identical to notes/tasks samples).
const HEADER = `import { pgTable, uuid, text, timestamp, boolean, integer, jsonb, vector, primaryKey } from "drizzle-orm/pg-core";
import { relations } from "drizzle-orm";
`;

const footer = (relExports = "") =>
  (relExports ? `\n${relExports}\n` : "\n") +
  "// Generated by scripts/gen-schemas.mjs — edit fields to match ADR-004/FEATURES.\n";

// ---- profiles (ADR-004: profiles_) ----
function profiles() {
  return HEADER + `
export const profiles = pgTable("profiles", {
  id: uuid("id").defaultRandom().primaryKey(),
  name: text("name").notNull(),
  color: text("color").notNull().default("#888888"),
  description: text("description"),
  isDefault: boolean("is_default").notNull().default(false),
  avatarUrl: text("avatar_url"),
  createdAt: timestamp("created_at", { mode: "string", withTimezone: true }).notNull().defaultNow(),
  updatedAt: timestamp("updated_at", { mode: "string", withTimezone: true }).notNull().defaultNow(),
});

export type ProfileRow = typeof profiles.$inferSelect;
export type ProfileInsert = typeof profiles.$inferInsert;
` + footer();
}

